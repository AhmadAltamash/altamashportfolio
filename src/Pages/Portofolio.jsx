const RoundedChevronButton = ({ onClick, isShowingMore }) => (
  <button
    onClick={onClick}
    aria-label={isShowingMore ? "Show fewer projects" : "Show more projects"}
    className="
      group relative w-12 h-12 rounded-full
      bg-gradient-to-r from-[#6366f1] to-[#a855f7]
      shadow-lg shadow-purple-500/20
      flex items-center justify-center
      hover:scale-110 active:scale-95
      transition-transform duration-300
    "
  >
    {!isShowingMore && (
      <span className="absolute inset-0 rounded-full bg-purple-500 opacity-30 animate-ping" />
    )}
    <ChevronDown
      className={`relative z-10 w-5 h-5 text-white transition-transform duration-300 ${
        isShowingMore ? "rotate-180" : "group-hover:translate-y-0.5"
      }`}
    />
  </button>
);

RoundedChevronButton.propTypes = {
  onClick: PropTypes.func.isRequired,
  isShowingMore: PropTypes.bool.isRequired,
};

function TabPanel({ children, value, index, ...other }) {
  return (
    <div
      role="tabpanel"
      hidden={value !== index}
      id={`full-width-tabpanel-${index}`}
      aria-labelledby={`full-width-tab-${index}`}
      {...other}
    >
      {value === index && (
        <Box sx={{ p: { xs: 1, sm: 3 } }}>
          <Typography>{children}</Typography>
        </Box>
      )}
    </div>
  );
}

TabPanel.propTypes = {
  children: PropTypes.node,
  index: PropTypes.number.isRequired,
  value: PropTypes.number.isRequired,
};

function a11yProps(index) {
  return {
    id: `full-width-tab-${index}`,
    "aria-controls": `full-width-tabpanel-${index}`,
  };
}

